function [tMs, angleDeg] = rt_generate_synthetic(opts)
%RT_GENERATE_SYNTHETIC Generate a SYNTHETIC joint-angle time series and export it.
%
%   [tMs, angleDeg] = rt_generate_synthetic(opts)
%
%   Model (identical to src/domain/synthetic.ts):
%       angle(t) = baseDeg + amplitudeDeg * (1 - cos(2*pi*t/periodS)) / 2 + noise
%       noise    ~ N(0, noiseSdDeg^2), reproducible via rng(seed, 'twister')
%   Values are clamped to [-180, 180] and rounded to 0.01 deg.
%
%   NOTE: MATLAB's random generator differs from the web app's, so the same seed gives
%   different noise in MATLAB and in the browser. Cross-checks are therefore done on the
%   ANALYSIS of identical files (see rt_verify_golden.m), not on generation.
%
%   opts fields (all optional):
%       joint        'shoulder'|'elbow'|'wrist'|'hip'|'knee'|'ankle'   (default 'knee')
%       side         'left'|'right'                                    (default 'right')
%       movement     must be supported for the joint                   (default 'flexion')
%       sampleRateHz sampling rate, 1..1000                            (default 50)
%       durationS    recording length in seconds                       (default 20)
%       baseDeg      starting angle                                    (default 5)
%       amplitudeDeg peak-to-peak movement                             (default 100)
%       periodS      seconds per repetition                            (default 4)
%       noiseSdDeg   Gaussian noise SD                                 (default 1)
%       seed         RNG seed                                          (default 1)
%       startTime    datetime in UTC                                   (default 2026-10-26 10:00:00 UTC)
%       outBase      output path without extension; writes .csv and .json (default: no files)
%
%   Example (MATLAB Online):
%       opts = struct('joint','shoulder','side','left','movement','abduction', ...
%                     'sampleRateHz',100,'durationS',15,'amplitudeDeg',140,'periodS',5, ...
%                     'noiseSdDeg',0.8,'seed',7,'outBase','shoulder_left_abduction_synthetic');
%       rt_generate_synthetic(opts);

cfg = rt_config();
if nargin < 1, opts = struct(); end
def = struct('joint','knee','side','right','movement','flexion','sampleRateHz',50, ...
    'durationS',20,'baseDeg',5,'amplitudeDeg',100,'periodS',4,'noiseSdDeg',1,'seed',1, ...
    'startTime',datetime(2026,10,26,10,0,0,'TimeZone','UTC'),'outBase','');
f = fieldnames(def);
for i = 1:numel(f)
    if ~isfield(opts, f{i}), opts.(f{i}) = def.(f{i}); end
end

% ---- validate configuration -------------------------------------------------------------
if ~isfield(cfg.movements, opts.joint)
    error('rt:joint', 'Unknown joint "%s".', opts.joint);
end
if ~any(strcmp(opts.side, {'left','right'}))
    error('rt:side', 'Side must be left or right.');
end
if ~any(strcmp(opts.movement, cfg.movements.(opts.joint)))
    error('rt:movement', 'Movement "%s" is not supported for the %s.', opts.movement, opts.joint);
end
if opts.sampleRateHz < 1 || opts.sampleRateHz > 1000
    error('rt:rate', 'sampleRateHz must be between 1 and 1000.');
end

% ---- generate ------------------------------------------------------------------------------
intervalMs = round(1000 / opts.sampleRateHz);
n = floor(opts.durationS * 1000 / intervalMs) + 1;
if n < cfg.minSamples || n > cfg.maxSamples
    error('rt:length', 'Generated %d samples; must be between %d and %d.', n, cfg.minSamples, cfg.maxSamples);
end
idx = (0:n-1)';
tS = idx * intervalMs / 1000;
rng(opts.seed, 'twister');
clean = opts.baseDeg + opts.amplitudeDeg * (1 - cos(2*pi*tS/opts.periodS)) / 2;
noisy = clean + opts.noiseSdDeg * randn(n, 1);
angleDeg = round(min(max(noisy, cfg.minAngleDeg), cfg.maxAngleDeg) * 100) / 100;

startMs = round(posixtime(opts.startTime) * 1000);
tMs = startMs + idx * intervalMs;

% ---- export --------------------------------------------------------------------------------
if ~isempty(opts.outBase)
    stamps = rt_format_timestamps(tMs);
    % CSV
    fid = fopen([opts.outBase '.csv'], 'w');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, 'timestamp,joint,side,movement,angleDeg\n');
    for k = 1:n
        fprintf(fid, '%s,%s,%s,%s,%s\n', stamps{k}, opts.joint, opts.side, opts.movement, num2str(angleDeg(k), '%.15g'));
    end
    clear cleanup;
    % JSON
    doc = struct();
    doc.format = cfg.formatId;
    doc.joint = opts.joint;
    doc.side = opts.side;
    doc.movement = opts.movement;
    doc.unit = 'deg';
    doc.source = 'simulation';
    doc.description = 'SYNTHETIC data generated by rt_generate_synthetic.m - not a measurement of any person.';
    doc.generator = struct('tool','MATLAB rt_generate_synthetic','sampleRateHz',opts.sampleRateHz, ...
        'durationS',opts.durationS,'baseDeg',opts.baseDeg,'amplitudeDeg',opts.amplitudeDeg, ...
        'periodS',opts.periodS,'noiseSdDeg',opts.noiseSdDeg,'seed',opts.seed);
    doc.samples = struct('timestamp', stamps, 'angleDeg', num2cell(angleDeg));
    fid = fopen([opts.outBase '.json'], 'w');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s', jsonencode(doc, 'PrettyPrint', true));
    clear cleanup;
    fprintf('Wrote %s.csv and %s.json (%d samples, SYNTHETIC)\n', opts.outBase, opts.outBase, n);
end
end

function stamps = rt_format_timestamps(tMs)
%Format epoch milliseconds as 2026-10-26T10:00:00.000Z
dt = datetime(tMs / 1000, 'ConvertFrom', 'posixtime', 'TimeZone', 'UTC');
dt.Format = 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z''';
stamps = cellstr(string(dt));
end
