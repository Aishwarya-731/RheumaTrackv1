import * as THREE from 'three';

/**
 * Smooth tapered limb: a lathe (surface of revolution) whose profile is resampled from a
 * spline, giving a muscle-like shape that is closed at both ends. Top at y = 0, bottom at y = −length.
 */
export function taperedLimb(length: number, rTop: number, rMid: number, rBot: number, radialSegments = 48): THREE.LatheGeometry {
  const ctrl = [
    new THREE.Vector2(0.0001, 0),
    new THREE.Vector2(rTop * 0.75, -length * 0.015),
    new THREE.Vector2(rTop, -length * 0.07),
    new THREE.Vector2(rMid, -length * 0.32),
    new THREE.Vector2((rMid + rBot) / 2, -length * 0.66),
    new THREE.Vector2(rBot, -length * 0.92),
    new THREE.Vector2(rBot * 0.7, -length * 0.985),
    new THREE.Vector2(0.0001, -length),
  ];
  const curve = new THREE.SplineCurve(ctrl);
  const pts = curve.getPoints(64).map((p) => new THREE.Vector2(Math.max(0.0001, p.x), p.y));
  // Lathe expects points ordered bottom→top for outward normals.
  pts.reverse();
  const geo = new THREE.LatheGeometry(pts, radialSegments);
  geo.computeVertexNormals();
  return geo;
}

/** Torso shell: lathe with an elliptical cross-section produced by scaling in x/z. */
export function torsoGeometry(): THREE.LatheGeometry {
  // Profile from pelvis base (y=0) to neck base (y≈0.5), radius = half-width at each height.
  const ctrl = [
    new THREE.Vector2(0.0001, -0.08),
    new THREE.Vector2(0.09, -0.07),
    new THREE.Vector2(0.148, -0.02),
    new THREE.Vector2(0.152, 0.04),
    new THREE.Vector2(0.128, 0.13),
    new THREE.Vector2(0.122, 0.19),
    new THREE.Vector2(0.142, 0.27),
    new THREE.Vector2(0.168, 0.35),
    new THREE.Vector2(0.176, 0.41),
    new THREE.Vector2(0.15, 0.46),
    new THREE.Vector2(0.075, 0.49),
    new THREE.Vector2(0.0001, 0.5),
  ];
  const pts = new THREE.SplineCurve(ctrl).getPoints(80).map((p) => new THREE.Vector2(Math.max(0.0001, p.x), p.y));
  const geo = new THREE.LatheGeometry(pts, 64);
  geo.computeVertexNormals();
  return geo;
}

/**
 * Flat ring sector (annulus) in a plane, described by two unit vectors: `from` (angle 0) and
 * `axis` (rotation axis). Points are generated by rotating `from` about `axis`, so the arc
 * lies exactly where the limb would point at each angle.
 */
export function arcSector(
  direction: (angleDeg: number) => [number, number, number],
  fromDeg: number,
  toDeg: number,
  innerR: number,
  outerR: number,
  steps = 64,
): THREE.BufferGeometry {
  const lo = Math.min(fromDeg, toDeg);
  const hi = Math.max(fromDeg, toDeg);
  const n = Math.max(2, Math.ceil(((hi - lo) / 180) * steps) + 1);
  const positions: number[] = [];
  const indices: number[] = [];
  for (let i = 0; i < n; i++) {
    const a = lo + ((hi - lo) * i) / (n - 1);
    const [x, y, z] = direction(a);
    positions.push(x * innerR, y * innerR, z * innerR, x * outerR, y * outerR, z * outerR);
    if (i > 0) {
      const b = (i - 1) * 2;
      indices.push(b, b + 1, b + 2, b + 1, b + 3, b + 2);
    }
  }
  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  geo.setIndex(indices);
  geo.computeVertexNormals();
  return geo;
}

/** Thin line along an arc (used for the outline of the range sector). */
export function arcLinePoints(direction: (angleDeg: number) => [number, number, number], fromDeg: number, toDeg: number, r: number, steps = 64): THREE.Vector3[] {
  const lo = Math.min(fromDeg, toDeg);
  const hi = Math.max(fromDeg, toDeg);
  const n = Math.max(2, Math.ceil(((hi - lo) / 180) * steps) + 1);
  const pts: THREE.Vector3[] = [];
  for (let i = 0; i < n; i++) {
    const [x, y, z] = direction(lo + ((hi - lo) * i) / (n - 1));
    pts.push(new THREE.Vector3(x * r, y * r, z * r));
  }
  return pts;
}
